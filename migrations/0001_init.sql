-- Source-of-truth schema. Elasticsearch is a derived read model built from it.

CREATE TABLE authors (
    id   text PRIMARY KEY,                      -- UUIDv7, generated by the app
    name text NOT NULL CHECK (name <> '')       -- NOT unique by design (see README)
);

-- Case-insensitive name -> ids lookup for the `author` filter.
CREATE INDEX authors_name_lower_idx ON authors (lower(name));

CREATE TABLE articles (
    id         text        PRIMARY KEY,         -- UUIDv7 (time-ordered => append-friendly B-tree)
    author_id  text        NOT NULL REFERENCES authors (id),
    title      text        NOT NULL,
    body       text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),  -- never changes
    -- Additions to the given table design (justified in README):
    updated_at timestamptz NOT NULL DEFAULT now(),  -- articles are edited
    version    bigint      NOT NULL DEFAULT 1       -- monotonic, used as ES external version
);

-- Global feed: "newest first" + keyset pagination on (created_at, id).
CREATE INDEX articles_created_at_id_idx ON articles (created_at DESC, id DESC);

-- Per-author feed: bounded scans even for the syndication account.
CREATE INDEX articles_author_created_at_id_idx ON articles (author_id, created_at DESC, id DESC);

-- Transactional outbox, written in the same transaction as the article.
CREATE TABLE article_outbox (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    article_id  text        NOT NULL,
    enqueued_at timestamptz NOT NULL DEFAULT now()
);
